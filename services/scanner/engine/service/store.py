"""
Scan store: one directory per scan, metadata in a JSON sidecar.

    <data>/scans/<scan_id>/
        scan.json       status + summary + timings
        input/          raw_lidar_cloud.ply, camera_poses.json, images/
        output/         floorplan.{json,svg,dxf,pdf}, room_model.{obj,glb}, ...

No database: the filesystem is the source of truth, so a scan survives a
restart and can be inspected or deleted with ordinary tools. Metadata writes
are atomic (temp file + rename) because the job worker and request handlers
both touch them.
"""

from __future__ import annotations

import json
import logging
import os
import re
import secrets
import shutil
import threading
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from .settings import settings

log = logging.getLogger(__name__)

# A scan id is generated by us and never interpolated from user input without
# passing this gate first — it is the only thing standing between the artifact
# routes and path traversal.
SCAN_ID_RE = re.compile(r"^[0-9]{8}-[0-9]{6}-[0-9a-f]{6}$")

STATUS_QUEUED = "queued"
STATUS_PROCESSING = "processing"
STATUS_READY = "ready"
STATUS_FAILED = "failed"

# Artifacts the API will serve, mapped to their media type and whether the
# browser should download rather than render them. Anything not listed is 404 —
# an allowlist, not a sanitised path.
ARTIFACTS: dict[str, tuple[str, bool]] = {
    "floorplan.json": ("application/json", False),
    "floorplan.svg": ("image/svg+xml", False),
    "floorplan.dxf": ("application/dxf", True),
    "floorplan.pdf": ("application/pdf", False),
    "colliders.json": ("application/json", False),
    "room_model.obj": ("model/obj", True),
    "room_model.glb": ("model/gltf-binary", True),
    "aligned_point_cloud.ply": ("application/octet-stream", True),
}

_lock = threading.RLock()


class ScanNotFound(Exception):
    """No scan with that id, or the id was not a well-formed scan id."""


def utcnow() -> str:
    return datetime.now(UTC).isoformat(timespec="microseconds")


def new_scan_id() -> str:
    """Sortable by creation time, with entropy so two scans in the same second never collide."""
    return f"{datetime.now(UTC):%Y%m%d-%H%M%S}-{secrets.token_hex(3)}"


def scan_dir(scan_id: str) -> Path:
    if not SCAN_ID_RE.match(scan_id):
        raise ScanNotFound(scan_id)
    return settings.scans_dir / scan_id


def input_dir(scan_id: str) -> Path:
    return scan_dir(scan_id) / "input"


def output_dir(scan_id: str) -> Path:
    return scan_dir(scan_id) / "output"


def meta_path(scan_id: str) -> Path:
    return scan_dir(scan_id) / "scan.json"


def create(name: str, source: str) -> dict:
    """Allocate a scan directory and its initial queued metadata."""
    scan_id = new_scan_id()
    with _lock:
        input_dir(scan_id).mkdir(parents=True, exist_ok=True)
        output_dir(scan_id).mkdir(parents=True, exist_ok=True)
        meta = {
            "id": scan_id,
            "name": name.strip() or f"Scan {scan_id[:8]}",
            "source": source,
            "status": STATUS_QUEUED,
            "created_at": utcnow(),
            "updated_at": utcnow(),
            "progress": {"step": 0, "total": 6, "message": "Queued"},
            "summary": None,
            "error": None,
            "duration_s": None,
        }
        write_meta(scan_id, meta)
    log.info("scan %s created (%s)", scan_id, source)
    return meta


def write_meta(scan_id: str, meta: dict) -> None:
    """Atomic write — a reader never sees a half-written metadata file."""
    path = meta_path(scan_id)
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(".json.tmp")
    tmp.write_text(json.dumps(meta, indent=2))
    os.replace(tmp, path)


def read_meta(scan_id: str) -> dict:
    path = meta_path(scan_id)
    if not path.exists():
        raise ScanNotFound(scan_id)
    try:
        return json.loads(path.read_text())
    except json.JSONDecodeError as exc:  # pragma: no cover - corrupted sidecar
        raise ScanNotFound(scan_id) from exc


def update(scan_id: str, **fields: Any) -> dict:
    """Read-modify-write a scan's metadata under the store lock."""
    with _lock:
        meta = read_meta(scan_id)
        meta.update(fields)
        meta["updated_at"] = utcnow()
        write_meta(scan_id, meta)
        return meta


def set_progress(scan_id: str, step: int, total: int, message: str) -> None:
    update(scan_id, progress={"step": step, "total": total, "message": message})


def listing() -> list[dict]:
    """All scans, newest first. Unreadable directories are skipped, not fatal."""
    if not settings.scans_dir.exists():
        return []
    scans = []
    for child in settings.scans_dir.iterdir():
        if not child.is_dir() or not SCAN_ID_RE.match(child.name):
            continue
        try:
            scans.append(read_meta(child.name))
        except ScanNotFound:
            log.warning("skipping scan dir without readable metadata: %s", child.name)
    scans.sort(key=lambda m: m.get("created_at", ""), reverse=True)
    return scans


def latest_ready() -> dict | None:
    """Most recent successfully processed scan — what the legacy routes serve."""
    return next((m for m in listing() if m.get("status") == STATUS_READY), None)


def delete(scan_id: str) -> None:
    target = scan_dir(scan_id)
    if not target.exists():
        raise ScanNotFound(scan_id)
    with _lock:
        shutil.rmtree(target, ignore_errors=True)
    log.info("scan %s deleted", scan_id)


def prune(keep: int | None = None) -> int:
    """
    Drop the oldest finished scans beyond the cap. Queued and in-flight scans
    are never pruned, so a burst of uploads cannot delete work in progress.
    """
    keep = settings.max_scans if keep is None else keep
    finished = [m for m in listing() if m.get("status") in (STATUS_READY, STATUS_FAILED)]
    removed = 0
    for meta in finished[keep:]:
        try:
            delete(meta["id"])
            removed += 1
        except ScanNotFound:  # pragma: no cover - raced with a manual delete
            pass
    return removed


def artifact_path(scan_id: str, name: str) -> Path:
    """Resolve an allowlisted artifact, or raise ScanNotFound."""
    if name not in ARTIFACTS:
        raise ScanNotFound(f"{scan_id}/{name}")
    path = output_dir(scan_id) / name
    if not path.exists():
        raise ScanNotFound(f"{scan_id}/{name}")
    return path


def frame_path(scan_id: str, filename: str) -> Path:
    """
    Resolve a capture frame image. The filename comes from floorplan.json
    (which we generated), but it is still treated as untrusted: basename only,
    extension allowlisted, and the resolved path must stay inside the scan.
    """
    base = os.path.basename(filename)
    if not base or base.startswith(".") or not base.lower().endswith((".jpg", ".jpeg", ".png")):
        raise ScanNotFound(f"{scan_id}/frames/{filename}")
    root = (input_dir(scan_id) / "images").resolve()
    path = (root / base).resolve()
    if not path.is_file() or root not in path.parents:
        raise ScanNotFound(f"{scan_id}/frames/{filename}")
    return path


def summarize(floorplan: dict) -> dict:
    """The handful of numbers the scan list and header badges show."""
    room = floorplan.get("room", {})
    openings = room.get("openings", []) or []
    scan = floorplan.get("scan", {}) or {}
    return {
        "area_sqm": room.get("area_sqm"),
        "area_sqft": room.get("area_sqft"),
        "perimeter_m": room.get("perimeter_m"),
        "ceiling_height_m": floorplan.get("ceiling_height_m"),
        "wall_count": len(room.get("walls", []) or []),
        "door_count": sum(1 for o in openings if o.get("type") == "door"),
        "window_count": sum(1 for o in openings if o.get("type") == "window"),
        "furniture_count": len(room.get("furniture_footprints", []) or []),
        "camera_view_count": len(scan.get("camera_views", []) or []),
        "point_count_fused": scan.get("point_count_fused"),
    }
